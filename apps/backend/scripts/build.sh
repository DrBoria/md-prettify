#!/usr/bin/env bash
# build.sh <vscode|webstorm> [dev]
#
# Compiles the IDE-agnostic backend, then the chosen IDE decorator package, and
# writes out/activate.js — the entry the IDE manifest points at. The decorator
# never imports the backend: this script is the only place the two meet.
#
# `dev` additionally wires the devtool MCP bridge into the entry. It is the only
# mode that mentions the devtool at all, so a shipped build carries neither the
# code nor the dependency.
set -euo pipefail

ide="${1:-}"
mode="${2:-prod}"
case "$ide" in
	vscode | webstorm) ;;
	*)
		echo "usage: scripts/build.sh <vscode|webstorm> [dev]" >&2
		exit 1
		;;
esac
case "$mode" in
	dev | prod) ;;
	*)
		echo "usage: scripts/build.sh <vscode|webstorm> [dev]" >&2
		exit 1
		;;
esac

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
app="$(dirname "$here")"
root="$(cd "$app/../.." && pwd)"
decorator="$root/packages/$ide-extension"

tsc_bin="$root/node_modules/.bin/tsc"

# A build must not keep the output of a file that no longer exists: `tsc` never
# deletes, so a renamed or moved module would linger in `out` and be loaded by
# the tests instead of the current one.
rm -rf "$app/out" "$decorator/out"

"$tsc_bin" -p "$app/tsconfig.json"
"$tsc_bin" -p "$decorator/tsconfig.json"

mkdir -p "$app/out"
mkdir -p "$decorator/out/apps/backend"

# write_activate <file> <decorator path> <backend path> <1|0 dev>
write_activate() {
	if [ "$4" = "1" ]; then
		devtool_require="const { bridgeLogs, startDevtool } = require('$2/debug-server.js');"
		devtool_start='
	// Dev only: every console call of this host goes to the devtool log buffer, and two
	// read-only commands expose the real state, so the MCP tools can verify the editor
	// without reading anything from disk.
	bridgeLogs();
	const devState = require("'"$app/out/dev-state.js"'");
	vscode.commands.registerCommand("md-prettify.devtoolOpen", async (file) => {
		await vscode.window.showTextDocument(vscode.Uri.file(file));
		return "opened " + file;
	});
	vscode.commands.registerCommand("md-prettify.devtoolState", () => {
		const payload = JSON.stringify({ decorations: devState.decorationsState(), texts: devState.textsState() });
		console.info("[md-prettify][state] " + payload);
		return payload;
	});
	const devtool = startDevtool(outputChannel);
	context.subscriptions.push({ dispose: function () { void devtool.stop(); } });'
	else
		devtool_require=''
		devtool_start=''
	fi
	cat >"$1" <<EOF
// Generated by scripts/build.sh for the $ide adapter ($mode). Do not edit.
// This file is the only place where the IDE adapter and the backend meet: the
// adapter package never imports the application.
const { createIde } = require('$2/ide-adapter.js');
const vscode = require('vscode');
const backend = require('$3');
$devtool_require

// activateBackend: reports a failed activation through the console, because a
// thrown activation otherwise only reaches the IDE's own log files.
const activateBackend = function (ide) {
	try {
		return backend.activate(ide);
	} catch (error) {
		console.error('[md-prettify] activation failed:', error);
		throw error;
	}
};

exports.activate = function (context) {
	const ide = createIde();
	const outputChannel = ide.createOutputChannel('MD Prettify Debug');
	context.subscriptions.push(outputChannel);$devtool_start
	context.subscriptions.push(...backend.registerCommands(ide));
	context.subscriptions.push(...backend.registerListeners(ide));
	return activateBackend(ide);
};

exports.deactivate = function () {
	backend.deactivate();
};
EOF
}

write_activate "$app/out/activate.js" \
	"../../../packages/$ide-extension/out/packages/$ide-extension" \
	'./index.js' \
	"$([ "$mode" = dev ] && echo 1 || echo 0)"
# the manifest points here, so this is the entry that follows the build mode
write_activate "$decorator/activate.js" \
	"./out/packages/$ide-extension" \
	"$app/out/index.js" \
	"$([ "$mode" = dev ] && echo 1 || echo 0)"
# the copy the adapter's own tests load never needs the devtool bridge
write_activate "$decorator/out/apps/backend/activate.js" \
	"../../packages/$ide-extension" \
	'../../../../../apps/backend/out/index.js' \
	0

echo "built $ide entry ($mode): $app/out/activate.js"
echo "built $ide test entry: $decorator/out/apps/backend/activate.js"
